#!/usr/bin/env node
/**
 * Builds deployment artifacts.
 *
 *  dist/paycheck-engine.js          External ES module for WordPress (cacheable)
 *  dist/paycheck-calculator.html    Standalone self-contained page
 *  dist/wp/*.html                   Copy-paste snippets for the WP editor
 *  dist/wp/schema.jsonld            Structured data for the calculator page
 *
 * The engine is emitted as an external file rather than inlined into a
 * WordPress page because wpautop mangles inline <script type="module"> blocks.
 * See docs/WORDPRESS-INTEGRATION.md.
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");
const DIST = join(ROOT, "dist");
const WPDIR = join(DIST, "wp");
mkdirSync(WPDIR, { recursive: true });

const read = (p) => readFileSync(join(ROOT, p), "utf8");

/**
 * Strips ESM syntax for single-file inlining.
 *
 * Fails loudly on local imports rather than deleting them. Silently removing
 * an import produces a bundle that throws at runtime in the browser, which is
 * far harder to diagnose than a build error.
 */
function stripModuleSyntax(src, label) {
  return src
    .replace(
      /^\s*import\s+(?:[^;'"]+?\s+from\s+)?["']([^"']+)["'];?\s*$/gm,
      (_m, spec) => {
        if (spec.startsWith(".") || spec.startsWith("/")) {
          throw new Error(
            `${label}: unresolved local import "${spec}". ` +
              `The bundler inlines only self-contained files. Either merge ${spec} ` +
              `into ${label}, or add it to the concatenation order in tools/build.mjs.`
          );
        }
        return ""; // bare external import (unused at build time)
      }
    )
    .replace(/^\s*export\s+/gm, "")
    .trim();
}

// ---- tax data ----
const federal = {};
for (const y of [2025, 2026]) federal[y] = JSON.parse(read(`src/data/federal/us-fed-${y}.json`));

const states = {};
const stateDir = join(ROOT, "src", "data", "states");
for (const f of readdirSync(stateDir)) {
  if (!f.endsWith(".json") || f === "index.json") continue;
  const rec = JSON.parse(readFileSync(join(stateDir, f), "utf8"));
  states[`${rec.jurisdiction}-${rec.tax_year}`] = rec;
}
const stateIndex = JSON.parse(read("src/data/states/index.json"));

const engineSrc = stripModuleSyntax(read("src/engine/calculator.js"), "calculator.js");
const uiSrc = stripModuleSyntax(read("src/ui/calculator-ui.js"), "calculator-ui.js");
const css = read("src/ui/calculator.css");

const DATA_BLOCK = `
const FEDERAL = ${JSON.stringify(federal)};
const STATES = ${JSON.stringify(states)};
const STATE_INDEX = ${JSON.stringify(stateIndex)};
const getFederal = (y) => FEDERAL[y];
const getState = (code, y) => STATES[\`\${code}-\${y}\`];
const getStateList = () => STATE_INDEX.states;
`;

const MOUNT_HELPER = `
/**
 * Convenience entry point: wires the engine into the UI.
 * Idempotent, so the inline call and auto-mount cannot double-mount.
 */
function mountCalculator(el) {
  if (!el || el.dataset.pcMounted === "1") return;
  el.dataset.pcMounted = "1";
  return mount(el, { calculate, getFederal, getState, getStateList });
}

/**
 * Auto-mount when a #paycheck-calculator container is present.
 * Lets WordPress load the engine via wp_enqueue_script_module with no inline
 * script at all, which sidesteps wpautop reformatting the JS.
 */
function autoMount() {
  const el = document.getElementById("paycheck-calculator");
  if (el) mountCalculator(el);
}
if (typeof document !== "undefined") {
  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", autoMount);
  } else {
    autoMount();
  }
}
`;

const EXPORTS =
  "export { calculate, bracketTax, marginalRate, PERIODS, FILING_STATUSES, " +
  "mount, template, mountCalculator, getFederal, getState, getStateList };";

// ---- 1. external engine module (WordPress) ----
const engineBundle = `/* paycheck-engine.js — generated by tools/build.mjs. Do not edit. */
${DATA_BLOCK}
${engineSrc}
${uiSrc}
${MOUNT_HELPER}
${EXPORTS}
`;
writeFileSync(join(DIST, "paycheck-engine.js"), engineBundle);

// ---- 2. standalone page ----
const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>Paycheck Calculator — Take-Home Pay After Taxes</title>
<meta name="description" content="Free US paycheck calculator. Estimate your take-home pay after federal tax, FICA, and state income tax. No signup required." />
<style>
${css}
</style>
</head>
<body>
<main id="paycheck-calculator" class="pc-app" aria-label="Paycheck calculator"></main>
<script type="module">
${DATA_BLOCK}
${engineSrc}
${uiSrc}
mountCalculator(document.getElementById("paycheck-calculator"));
</script>
</body>
</html>
`;
writeFileSync(join(DIST, "paycheck-calculator.html"), html);

// ---- 3. WordPress snippets ----
// Server-render the form so the inputs and state list are in the initial HTML
// (crawlable), rather than injected by JS.
const { template } = await import("../src/ui/calculator-ui.js");
const formHtml = template(stateIndex.states);

writeFileSync(
  join(WPDIR, "1-paycheck-calculator-page.html"),
  `<!-- Paste into the Page body. Use the Code Editor, not the Visual editor. -->
<div id="paycheck-calculator" class="pc-app" aria-label="Paycheck calculator">
${formHtml}
</div>

<script type="module">
  import { mountCalculator } from "/wp-content/uploads/tools/paycheck-engine.js";
  mountCalculator(document.getElementById("paycheck-calculator"));
</script>
`
);

writeFileSync(
  join(WPDIR, "2-finance-hub-page.html"),
  `<!-- Paste into the /finance hub Page body. -->
<h2>Money &amp; Pay Calculators</h2>
<p>Free tools for understanding your pay, taxes, and take-home income. No signup, no data leaves your browser.</p>

<ul>
  <li>
    <h3><a href="/finance/paycheck-calculator">Paycheck Calculator</a></h3>
    <p>Estimate your take-home pay per period after federal income tax, FICA, and state income tax.</p>
  </li>
</ul>
`
);

writeFileSync(
  join(WPDIR, "3-schema.jsonld"),
  JSON.stringify(
    {
      "@context": "https://schema.org",
      "@graph": [
        {
          "@type": "WebApplication",
          name: "Paycheck Calculator",
          url: "https://afreetools.com/finance/paycheck-calculator",
          applicationCategory: "FinanceApplication",
          operatingSystem: "All",
          browserRequirements: "Requires JavaScript",
          offers: { "@type": "Offer", price: "0", priceCurrency: "USD" },
          description:
            "Free US paycheck calculator. Estimate take-home pay after federal income tax, Social Security, Medicare, and state income tax.",
        },
        {
          "@type": "BreadcrumbList",
          itemListElement: [
            { "@type": "ListItem", position: 1, name: "Home", item: "https://afreetools.com/" },
            { "@type": "ListItem", position: 2, name: "Finance", item: "https://afreetools.com/finance/" },
            {
              "@type": "ListItem",
              position: 3,
              name: "Paycheck Calculator",
              item: "https://afreetools.com/finance/paycheck-calculator",
            },
          ],
        },
        {
          "@type": "FAQPage",
          mainEntity: [
            {
              "@type": "Question",
              name: "How accurate is this paycheck calculator?",
              acceptedAnswer: {
                "@type": "Answer",
                text: "It produces an estimate for planning. It covers federal income tax, Social Security, Medicare, and state income tax, but not local or paid-leave taxes. Your employer's payroll system may withhold a different amount.",
              },
            },
            {
              "@type": "Question",
              name: "Why is my actual paycheck different from this estimate?",
              acceptedAnswer: {
                "@type": "Answer",
                text: "It depends on local or municipal income taxes, state disability or paid-leave programs, benefit deductions, and the withholding method your employer uses.",
              },
            },
          ],
        },
      ],
    },
    null,
    2
  ) + "\n"
);

writeFileSync(
  join(WPDIR, "4-enqueue-snippet.php"),
  `<?php
/**
 * Optional: load the engine without pasting any <script> into the page body.
 *
 * Inline <script type="module"> is the riskiest part of a WordPress install,
 * because the editor can reformat it and break the JS. The engine auto-mounts
 * itself, so enqueueing it alone is enough. Nothing inline, nothing to mangle.
 *
 * Where to put this, pick ONE:
 *   a) A child theme's functions.php          (survives parent theme updates)
 *   b) A small site-specific plugin in wp-content/plugins/
 *   c) Code Snippets plugin (Code Snippets -> Add New)
 *
 * Do NOT paste into the parent GeneratePress theme — a theme update erases it.
 */

add_action( 'wp_enqueue_scripts', function () {
    // Loads on the calculator page only, so other pages stay unaffected.
    if ( ! is_page( 'paycheck-calculator' ) ) {
        return;
    }

    // Registers and prints as <script type="module" src="...">.
    wp_enqueue_script_module(
        'paycheck-engine',
        content_url( '/uploads/tools/paycheck-engine.js' ),
        array(),
        '1.0.0'   // bump this after re-uploading to bust browser cache
    );
} );
`
);

const kb = (b) => (Buffer.byteLength(b) / 1024).toFixed(1) + " KB";
console.log("Built:");
console.log(`  dist/paycheck-engine.js          ${kb(engineBundle)}  (external module for WordPress)`);
console.log(`  dist/paycheck-calculator.html    ${kb(html)}  (standalone)`);
console.log(`  dist/wp/1-paycheck-calculator-page.html`);
console.log(`  dist/wp/2-finance-hub-page.html`);
console.log(`  dist/wp/3-schema.jsonld`);
console.log(`  dist/wp/4-enqueue-snippet.php`);
